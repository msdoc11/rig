<?php

declare(strict_types=1);

namespace Rig\Attr;

/**
 * Компонент загружается после того, как страница уже открылась: сначала виден скелетон (блок <skeleton>),
 * затем браузер сам запрашивает данные (mount() выполняется в этом запросе).
 * Так тяжёлые выборки не задерживают открытие страницы.
 *
 * С ssr: true при первой загрузке страницы (и для поисковиков) компонент рендерится сразу с данными,
 * а лениво грузится только при переходах между страницами.
 */
#[\Attribute(\Attribute::TARGET_CLASS)]
final class Lazy
{
    public function __construct(public readonly bool $ssr = false)
    {
    }
}
